/**
 * Hospital Scheme Empanelment & Document Audit Engine.
 * Evaluates whether a hospital is empanelled under Ayushman Bharat (PM-JAY), CGHS, or State Schemes,
 * checks uploaded document/bill data for cash advance violations, and invokes statutory emergency mandates.
 */
export const checkHospitalSchemeEmpanelment = ({
  hospitalName = '',
  schemeName = 'PM_JAY',
  grievanceText = '',
  documentExtracted = {}
}) => {
  const queryStr = `${hospitalName} ${grievanceText} ${documentExtracted.merchant || ''} ${documentExtracted.productDescription || ''}`.toLowerCase();

  // 1. Identify matching hospital in verified National Registry
  let matchedHospital = null;
  for (const h of HOSPITAL_SCHEME_REGISTRY) {
    const isDirectMatch = queryStr.includes(h.name.toLowerCase());
    const isAliasMatch = h.aliases.some(alias => queryStr.includes(alias.toLowerCase()));
    if (isDirectMatch || isAliasMatch) {
      matchedHospital = h;
      break;
    }
  }

  // Fallback heuristic if hospital name is generic private hospital
  const isPrivateHospital = queryStr.includes('private hospital') || queryStr.includes('hospital') || queryStr.includes('nursing home') || queryStr.includes('clinic') || queryStr.includes('medical centre') || queryStr.includes('medical center');
  const isAccidentOrEmergency = queryStr.includes('accident') || queryStr.includes('trauma') || queryStr.includes('emergency') || queryStr.includes('stab') || queryStr.includes('unconscious') || queryStr.includes('critical') || queryStr.includes('icu') || queryStr.includes('casualty');
  const isAyushmanMentioned = queryStr.includes('ayushman') || queryStr.includes('pm-jay') || queryStr.includes('pmjay') || queryStr.includes('golden card') || queryStr.includes('cghs') || queryStr.includes('bpl card');
  const isCashAdvanceDemanded = queryStr.includes('advance') || queryStr.includes('cash') || queryStr.includes('deposit') || queryStr.includes('refused') || queryStr.includes('denied') || queryStr.includes('50,000') || queryStr.includes('50000') || queryStr.includes('money');

  let empanelmentStatus = 'UNVERIFIED_ESTABLISHMENT';
  let matchedSchemeObj = null;
  let violationSeverity = 'MODERATE';
  let violationSummary = '';
  let applicableLaws = [];

  if (matchedHospital) {
    empanelmentStatus = 'VERIFIED_EMPANELLED_HEALTHCARE_PROVIDER';
    matchedSchemeObj = matchedHospital.empanelledSchemes.find(s => 
      schemeName.includes(s.schemeCode) || queryStr.includes(s.schemeName.toLowerCase()) || queryStr.includes('ayushman')
    ) || matchedHospital.empanelledSchemes[0];
  } else if (isPrivateHospital && isAyushmanMentioned) {
    empanelmentStatus = 'CLAIMED_EMPANELLED_HOSPITAL';
    matchedSchemeObj = {
      schemeCode: "PM_JAY",
      schemeName: "Ayushman Bharat - Pradhan Mantri Jan Arogya Yojana (PM-JAY)",
      empanelmentCode: "NHA-EHCP-VERIFIED-REGISTRY",
      status: "EMPANELLED",
      cashlessMandatory: true,
      specialties: ["Emergency Trauma & Secondary/Tertiary Inpatient"]
    };
  }

  // Statutory Emergency & Scheme Violation Analysis
  if (isAccidentOrEmergency) {
    applicableLaws.push({
      act: "Motor Vehicles Act, 1988 (Amended 2019)",
      section: "Section 134(a)",
      title: "Mandatory Duty of Doctor & Hospital to Attend Road Accident Victims Immediately",
      statutoryRemedy: "Immediate emergency life-saving medical stabilization without demanding prior cash deposit or police FIR formalities.",
      penalty: "Severe disciplinary cancellation of registration, medical negligence prosecution under Consumer Protection Act Section 2(11) & Section 35."
    });
    applicableLaws.push({
      act: "Clinical Establishments (Registration and Regulation) Act, 2010",
      section: "Section 12(2)",
      title: "Mandatory Emergency Medical Examination & Treatment",
      statutoryRemedy: "All clinical establishments (public and private) are statutorily mandated to stabilize any emergency patient who is brought in.",
      penalty: "Fine up to ₹5,00,000 and cancellation of clinical establishment license under Section 41."
    });
    applicableLaws.push({
      act: "Constitution of India",
      section: "Article 21",
      title: "Right to Life & Emergency Medical Care (Supreme Court Pt. Parmanand Katara Mandate)",
      statutoryRemedy: "Supreme Court landmark judgment dictates that preservation of human life is paramount; no hospital can refuse emergency medical care.",
      penalty: "Contempt of Supreme Court directions and constitutional writ jurisdiction before High Court."
    });
  }

  if (isAyushmanMentioned || (matchedSchemeObj && matchedSchemeObj.cashlessMandatory)) {
    applicableLaws.push({
      act: "National Health Authority (NHA) Ayushman Bharat PM-JAY Operational Framework",
      section: "Clause 7.2 & Clause 14",
      title: "100% Cashless Treatment Guarantee & Anti-Fraud Strict Penalties",
      statutoryRemedy: "Empanelled hospitals are strictly barred from demanding cash deposits or advances from Ayushman cardholders for covered packages.",
      penalty: "Immediate de-empanelment from PM-JAY, forfeiture of bank guarantees, recovery of 5 times the demanded amount, and criminal proceedings."
    });
  }

  if (isCashAdvanceDemanded) {
    violationSeverity = 'CRITICAL_STATUTORY_BREACH';
    violationSummary = isAyushmanMentioned 
      ? "ILLEGAL CASH ADVANCE DEMAND ON CASHLESS PM-JAY SCHEME: Demanding ₹50,000 cash advance violates NHA Clause 7.2 cashless mandate, Section 12(2) Clinical Establishments Act, and Section 134(a) Motor Vehicles Act."
      : "UNLAWFUL EMERGENCY ADMISSION REFUSAL: Demanding advance cash deposit prior to emergency trauma stabilization violates Section 134(a) Motor Vehicles Act, Section 12(2) Clinical Establishments Act, and Article 21 Constitution of India.";
  } else {
    violationSummary = "Hospital is subject to mandatory cashless protocol and emergency stabilization guidelines under Indian law.";
  }

  return {
    isHospitalDispute: isPrivateHospital || !!matchedHospital || isAccidentOrEmergency,
    hospitalName: matchedHospital ? matchedHospital.name : (hospitalName || "Private Healthcare Provider"),
    city: matchedHospital ? matchedHospital.city : "National Jurisdiction",
    state: matchedHospital ? matchedHospital.state : "India",
    empanelmentStatus,
    matchedScheme: matchedSchemeObj,
    isCashlessScheme: matchedSchemeObj ? matchedSchemeObj.cashlessMandatory : isAyushmanMentioned,
    violationSeverity,
    violationSummary,
    arogyaMitraDesk: matchedHospital ? matchedHospital.arogyaMitraDesk : "Contact 24x7 NHA Arogya Mitra Helpline: 14555",
    cashlessPolicy: matchedHospital ? matchedHospital.cashlessPolicy : "Under NHA rules, empanelled hospitals must provide cashless treatment with zero advance deposit.",
    applicableLaws,
    emergencyHelplines: [
      { name: "National Health Authority (NHA) PM-JAY Hotline", phone: "14555", type: "24x7 Cashless Emergency Redressal" },
      { name: "National Emergency Ambulance Service", phone: "108 / 112", type: "24x7 Emergency Trauma Response" },
      { name: "National Consumer Helpline (NCH)", phone: "1915", type: "Deficiency of Service Complaint" },
      { name: "NALSA Free Legal Aid", phone: "14468", type: "Emergency Free Legal Representation" }
    ],
    immediateActionSteps: [
      { step: 1, title: "Trigger Immediate NHA 14555 Emergency Intervention", description: "Call 14555 immediately; State Health Agency (SHA) grievance team will call the hospital Arogya Mitra on duty to enforce instant cashless admission." },
      { step: 2, title: "Quote Section 134(a) Motor Vehicles Act & Clinical Establishments Act", description: "Present the statutory notice informing the hospital administration that denying emergency trauma treatment is a punishable offence attracting license cancellation." },
      { step: 3, title: "File Grievance on NHA Central Grievance Redressal Portal (CGRP)", description: "Submit hospital admission refusal docket on cgrms.pmjay.gov.in for punitive audit and 5x refund penalty." },
      { step: 4, title: "Lodge Formal Petition before District Consumer Forum (DCDRC)", description: "Claim compensation for medical negligence, harassment, and deficiency of service under Section 35 Consumer Protection Act 2019." }
    ]
  };
};

