const LanguageContext = createContext();

export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState('en');

  const rawT = TRANSLATIONS[language] || TRANSLATIONS.en;
  
  // Resilient proxy to guarantee zero undefined text across any language
  const t = new Proxy(rawT, {
    get: (target, prop) => {
      if (prop in target && target[prop] !== undefined && target[prop] !== '') {
        return target[prop];
      }
      return TRANSLATIONS.en[prop] || '';
    }
  });

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, supportedLanguages: Object.keys(TRANSLATIONS) }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
